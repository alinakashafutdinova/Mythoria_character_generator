def P(txt='',bold=False):
    p=d.add_paragraph();p.alignment=WD_ALIGN_PARAGRAPH.JUSTIFY
    r=p.add_run(txt);r.bold=bold
    return p

def H(txt):d.add_heading(txt,1)
def H2(txt):d.add_heading(txt,2)
def L(items):
    for x in items:
        p=d.add_paragraph(style='List Bullet');p.add_run(x)

def T(headers,rows,width=None):
    tb=d.add_table(rows=1,cols=len(headers));tb.style='Light Shading Accent 1';tb.alignment=WD_TABLE_ALIGNMENT.CENTER
    for c,h in zip(tb.rows[0].cells,headers):c.text=h
    for row in rows:
        cells=tb.add_row().cells
        for c,v in zip(cells,row):c.text=str(v)
    for row in tb.rows:
        for cell in row.cells:
            cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            for p in cell.paragraphs:
                p.paragraph_format.space_after=Pt(1)
                for r in p.runs:r.font.size=Pt(9)
    return tb

def page():d.add_page_break()

def image(name,width=14):
    p=d.add_paragraph();p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(str(ROOT/'diagrams'/name),width=Cm(width))

def cap(txt):
    p=d.add_paragraph(txt);p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    for r in p.runs:r.italic=True;r.font.size=Pt(9)

